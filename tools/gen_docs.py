"""Generate the reference docs that must always match the code:  python tools/gen_docs.py
   docs/API_REFERENCE.md   (modules, classes, functions, signatures, docstrings of astrax/)
   docs/FILE_FORMATS.md    (every dataclass field + defaults of the JSON formats, sample files)
   docs/VALIDATION.md      (every automated test, grouped by area)
"""
import ast, dataclasses, importlib, inspect, json, os, pkgutil, sys, textwrap

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."); sys.path.insert(0, ROOT); DOCS = os.path.join(ROOT, "docs")


def first(doc, n=1):
    if not doc: return ""
    paras = inspect.cleandoc(doc).split("\n\n"); return " ".join(" ".join(p.split()) for p in paras[:n])


def api():
    import astrax
    out = ["# API reference (generated)", "", "Generated by `tools/gen_docs.py` from the docstrings in `astrax/`. The engine has **no Qt / OpenGL imports** and can be used on its own:", "",
           "```python", "from astrax.simulation import Simulation, LaunchConfig, SimConfig", "from astrax.missions import earth_leo", "L, plan = earth_leo()", "sim = Simulation(launch=L, plan=plan, config=SimConfig(dt_mode='auto'))",
           "while not sim.terminal() and sim.phase_idx < len(plan) - 1: sim.step()", "print(sim.telemetry()['periapsis_alt_m'])", "```", ""]
    for m in sorted(pkgutil.iter_modules(astrax.__path__), key=lambda x: x.name):
        mod = importlib.import_module(f"astrax.{m.name}"); out += [f"## `astrax.{m.name}`", "", first(mod.__doc__, 3), ""]
        for name, obj in inspect.getmembers(mod):
            if name.startswith("_") or getattr(obj, "__module__", "") != mod.__name__: continue
            if inspect.isclass(obj):
                out += [f"### class `{name}`", "", first(obj.__doc__), ""]
                if dataclasses.is_dataclass(obj):
                    out += ["| field | type | default |", "|---|---|---|"] + [f"| `{f.name}` | `{getattr(f.type, '__name__', f.type)}` | `{'(factory)' if f.default is dataclasses.MISSING and f.default_factory is not dataclasses.MISSING else f.default}` |" for f in dataclasses.fields(obj)] + [""]
                for mn, mo in inspect.getmembers(obj, inspect.isfunction):
                    if mn.startswith("_") or mo.__qualname__.split(".")[0] != name: continue
                    try: sig = str(inspect.signature(mo))
                    except Exception: sig = "(...)"
                    out += [f"- **`{mn}{sig}`** - {first(mo.__doc__)}"]
                out += [""]
            elif inspect.isfunction(obj):
                try: sig = str(inspect.signature(obj))
                except Exception: sig = "(...)"
                out += [f"### `{name}{sig}`", "", first(obj.__doc__, 2), ""]
    open(os.path.join(DOCS, "API_REFERENCE.md"), "w", encoding="utf-8").write("\n".join(out))


def formats():
    from astrax.rocket import Rocket, Stage, Engine, Nose, default_rocket
    from astrax.structure import Limits
    from astrax.simulation import LaunchConfig, Phase, SimConfig
    from astrax.missions import earth_leo
    from astrax import project
    out = ["# File formats (generated)", "", "All files are UTF-8 JSON, human-readable, and carry an `astrax_format` tag. Unknown/missing fields fall back to the defaults below, so older files keep loading.", "",
           "| Format tag | Written by | Contains |", "|---|---|---|", "| `rocket/1` | Rocket designer > Save design | one rocket |", "| `scenario/1` | File > Save scenario | rocket + launch + flight plan + sim config + planet overrides |",
           "| `planets/1` | Planet inspector > Save | edited planet parameters |", "| `session/1` | Telemetry > Save session | recorded telemetry arrays, events, units |", "| `.csv` | Telemetry > Export CSV | one row per sample, units in the headers |", ""]
    for cls in (Rocket, Stage, Engine, Nose, Limits, LaunchConfig, Phase, SimConfig):
        out += [f"## {cls.__name__}", "", first(cls.__doc__), "", "| field | type | default |", "|---|---|---|"]
        for f in dataclasses.fields(cls):
            d = "(factory)" if f.default is dataclasses.MISSING and f.default_factory is not dataclasses.MISSING else f.default
            out.append(f"| `{f.name}` | `{getattr(f.type, '__name__', f.type)}` | `{d}` |")
        out.append("")
    r = default_rocket(); d = r.to_dict(); d["stages"] = d["stages"][:1]
    out += ["## Example: rocket file (first stage only)", "", "```json", json.dumps({"astrax_format": "rocket/1", **d}, indent=2)[:3000], "```", ""]
    L, plan = earth_leo()
    out += ["## Example: flight plan", "", "```json", json.dumps([dataclasses.asdict(p) for p in plan], indent=2), "```", ""]
    out += ["## Flight-plan modes and end conditions", "", "Modes: `fixed_local`, `pitch_program`, `gravity_turn`, `ascent_hold`, `powered_landing`, `prograde`, `retrograde`, `normal`, `antinormal`, `radial_out`, `radial_in`, `coast`, `hold`.", "",
            "End conditions (`until`, any satisfied ends the phase): `duration_s`, `dv_mps`, `altitude_m`, `speed_mps`, `apoapsis_alt_m`, `periapsis_alt_m`, `at_apoapsis`, `burnout`, `stages_jettisoned`.", "",
            "Start modes (`LaunchConfig.start_mode`): `pad`, `orbit`, `hover`, `transfer`.", ""]
    open(os.path.join(DOCS, "FILE_FORMATS.md"), "w", encoding="utf-8").write("\n".join(out))


def validation():
    src = open(os.path.join(ROOT, "tests", "test_physics.py"), encoding="utf-8").read(); tree = ast.parse(src)
    out = ["# Validation (generated)", "", "Every automated test, grouped by area. Run all of them with `python -m unittest discover -s tests -v`.", "",
           "> Passing tests validate the **implementation against analytic/reference solutions**. They do not make AstraX a validated mission-analysis tool; see PHYSICS.md for the modelling limits.", ""]
    total = 0
    for cls in [n for n in tree.body if isinstance(n, ast.ClassDef)]:
        tests = [f for f in cls.body if isinstance(f, ast.FunctionDef) and f.name.startswith("test_")]
        if not tests: continue
        out += [f"## {cls.name}", "", "| test | what it checks |", "|---|---|"]
        for f in tests:
            total += 1; doc = ast.get_docstring(f) or ""; cm = ""
            line = src.splitlines()[f.lineno - 1]
            if "#" in line: cm = line.split("#", 1)[1].strip()
            out.append(f"| `{f.name}` | {doc or cm or f.name.replace('test_', '').replace('_', ' ')} |")
        out.append("")
    out.insert(2, f"**{total} tests.**\n")
    open(os.path.join(DOCS, "VALIDATION.md"), "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    api(); formats(); validation(); print("docs generated")
